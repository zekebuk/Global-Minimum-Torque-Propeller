"""``prandtl optimize-molding``: optimise a design's thickness schedule for injection-molded CFRP.

The base design's aero and sections stages run (cached), the thickness schedule is optimised
against the frequency, stress, deflection, and molding constraints, and the result is written as a
new design YAML. Its downstream stages (cad, dfm, fea, modal) then confirm the result.
"""

from __future__ import annotations

import copy
import csv
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from prandtl_prop import config
from prandtl_prop.design import apply_override, design_from_dict
from prandtl_prop.manufacturing.injection import MoldingRules
from prandtl_prop.manufacturing.materials import preset
from prandtl_prop.manufacturing.optimize import CONTROL_R_R, OptimisationResult, ThicknessProblem, optimise, with_material
from prandtl_prop.pipeline import design_sections, run_design
from prandtl_prop.runs import RunStore


@dataclass(frozen=True)
class MoldingOptimisation:
    result: OptimisationResult
    design_path: Path | None
    report_path: Path


def optimize_for_molding(
    design_file: Path,
    *,
    material: str,
    overrides: list[str] | None = None,
    store: RunStore | None = None,
    rpm_band: tuple[float, float] = (0.9, 1.1),
    margin: float = 0.10,
    max_section_thickness_m: float = 0.0065,
    trailing_edge_thickness_m: float = 0.0006,
    min_scale: float = 1.0,
    output: Path | None = None,
    model_cushion: float = 0.01,
) -> MoldingOptimisation:
    store = store or RunStore()
    data = yaml.safe_load(Path(design_file).read_text(encoding="utf-8")) or {}
    for override in overrides or []:
        apply_override(data, override)
    base_data = copy.deepcopy(data)
    base_data.setdefault("airfoils", {})
    base_data["airfoils"]["thickness_scale"] = []
    base_data["airfoils"]["trailing_edge_thickness_m"] = None
    base = design_from_dict(base_data)
    outcomes = run_design(base, ["sections"], store=store)
    aero = outcomes["aero"].run
    sections = design_sections(base, aero)
    with aero.output("stations.csv").open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    props = preset(material)
    rules = MoldingRules(min_trailing_edge_thickness_m=trailing_edge_thickness_m, max_section_thickness_m=max_section_thickness_m)
    problem = ThicknessProblem(
        sections,
        rows,
        blade_count=base.operating_point.blade_count,
        rpm=base.operating_point.rpm,
        rho_air=base.operating_point.rho_kg_m3,
        material=props,
        rules=rules,
        trailing_edge_thickness_m=trailing_edge_thickness_m,
        rpm_band=rpm_band,
        margin=margin,
        stress_safety_factor=base.molding.stress_safety_factor,
        max_tip_deflection_m=base.molding.max_tip_deflection_fraction * base.operating_point.radius_m,
        radius_m=base.operating_point.radius_m,
        model_cushion=model_cushion,
        root_geometry=base.root.geometry() if base.root.enabled else None,
    )
    result = optimise(problem, bounds=(min_scale, 2.0))

    folder = store.root / base.name / "molding_optimisation"
    folder.mkdir(parents=True, exist_ok=True)
    torque = float(aero.metrics["torque_Nm"])
    report: dict[str, Any] = {
        "base_design": str(design_file),
        "overrides": overrides or [],
        "material": props,
        "rpm_band": [rpm_band[0] * base.operating_point.rpm, rpm_band[1] * base.operating_point.rpm],
        "frequency_margin": margin,
        "model_cushion": model_cushion,
        "higher_mode_cushion": problem.other_margin - margin,
        "max_section_thickness_m": max_section_thickness_m,
        "trailing_edge_thickness_m": trailing_edge_thickness_m,
        "min_thickness_scale": min_scale,
        "baseline": _summary(result.baseline, torque),
        "southwell_coefficient": result.southwell_k,
        "baseline_f0_hz": result.f0_baseline_hz,
        "windows": result.attempts,
        "aero_run": aero.key,
    }
    design_path = None
    if result.best is not None:
        control = [float(v) for v in result.best.control]
        report["optimised"] = _summary(result.best, torque)
        report["window"] = f"{result.window.lower_harmonic}P-{result.window.lower_harmonic + 1}P"
        report["thickness_scale_control_points"] = [[r, s] for r, s in zip(CONTROL_R_R, control, strict=True)]
        optimised = with_material(copy.deepcopy(data), props)
        optimised["name"] = f"{base.name}_{material.replace('-', '_')}"
        optimised["description"] = (
            f"{base.name} thickness-optimised for injection-molded {props['name']} ({report['window']} flap placement over "
            f"{rpm_band[0]:.2f}-{rpm_band[1]:.2f} x design rpm). Generated by prandtl optimize-molding."
        )
        optimised.setdefault("airfoils", {})
        optimised["airfoils"]["thickness_scale"] = [[float(r), round(s, 4)] for r, s in zip(CONTROL_R_R, control, strict=True)]
        optimised["airfoils"]["trailing_edge_thickness_m"] = trailing_edge_thickness_m
        optimised["molding"] = {
            **optimised.get("molding", {}),
            "min_trailing_edge_thickness_m": trailing_edge_thickness_m,
            "max_section_thickness_m": max_section_thickness_m,
            "operating_rpm_fractions": list(rpm_band),
            "frequency_margin": margin,
        }
        design_from_dict(copy.deepcopy(optimised))  # validate before writing
        design_path = output or folder / f"{optimised['name']}.yaml"
        design_path.parent.mkdir(parents=True, exist_ok=True)
        header = "# Generated by `prandtl optimize-molding`; see the report next to the source run for constraints and assumptions.\n"
        design_path.write_text(header + yaml.safe_dump(optimised, sort_keys=False), encoding="utf-8")
        report["design_file"] = str(design_path)
    report_path = folder / f"report_{material}.json"
    report_path.write_text(json.dumps(report, indent=2, default=float) + "\n", encoding="utf-8")
    return MoldingOptimisation(result, design_path, report_path)


def _summary(evaluation, torque: float) -> dict[str, Any]:
    return {
        "profile_torque_penalty_Nm": evaluation.profile_torque_penalty_Nm,
        "profile_torque_penalty_fraction": evaluation.profile_torque_penalty_Nm / torque,
        "blade_mass_kg": evaluation.blade_mass_kg,
        "flap1_hz_over_band": [float(v) for v in evaluation.flap1_hz],
        "max_stress_Pa": evaluation.max_stress_Pa,
        "tip_deflection_m": evaluation.tip_deflection_m,
        "molding": evaluation.molding,
    }


__all__ = ["MoldingOptimisation", "optimize_for_molding", "config"]
