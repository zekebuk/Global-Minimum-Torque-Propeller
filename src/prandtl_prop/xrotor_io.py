"""Discovery and reporting helpers for optional XROTOR comparison artifacts."""

from __future__ import annotations

import shutil
from pathlib import Path

from prandtl_prop import config


def discover_xrotor_artifacts(root: Path = config.FINAL_AERO_DIR) -> list[Path]:
    """Return available XROTOR-related files in the final thesis output tree."""

    if not root.exists():
        return []
    return sorted(path for path in root.glob("*xrotor*") if path.is_file())


def copy_xrotor_figure(output_dir: Path = config.OUTPUT_FIGURES_DIR) -> list[Path]:
    """Copy the final XROTOR/BEMT comparison figure to the clean figure folder when present."""

    output_dir.mkdir(parents=True, exist_ok=True)
    copied: list[Path] = []
    for suffix in ("png", "pdf"):
        source = config.FINAL_AERO_DIR / f"xrotor_vs_bemt_model_difference.{suffix}"
        if source.exists():
            destination = output_dir / f"fig_xrotor_bemt_comparison.{suffix}"
            shutil.copy2(source, destination)
            copied.append(destination)
    return copied


def write_xrotor_report(output_path: Path) -> Path:
    """Write a concise report describing available XROTOR artifacts and limitations."""

    artifacts = discover_xrotor_artifacts()
    copied = copy_xrotor_figure()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# XROTOR Comparison Report",
        "",
        "XROTOR artifacts are optional numerical comparison files generated by external software.",
        "They are not experimental validation and do not provide acoustic SPL validation.",
        "",
        f"Artifact count: {len(artifacts)}",
        "",
    ]
    if artifacts:
        lines.append("## Available Files")
        lines.extend(f"- `{path.relative_to(config.PROJECT_ROOT)}`" for path in artifacts)
        lines.append("")
    if copied:
        lines.append("## Clean Figure Copies")
        lines.extend(f"- `{path.relative_to(config.PROJECT_ROOT)}`" for path in copied)
        lines.append("")
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return output_path
