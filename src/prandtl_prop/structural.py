"""Discovery and reporting helpers for structural screening artifacts."""

from __future__ import annotations

import shutil
from pathlib import Path

from prandtl_prop import config


def discover_structural_artifacts() -> list[Path]:
    """Return selected final structural screening files."""

    roots = [config.FINAL_STRUCTURAL_DIR, config.RESULTS_DIR / "fea"]
    artifacts: list[Path] = []
    for root in roots:
        if root.exists():
            artifacts.extend(path for path in root.rglob("*") if path.is_file())
    return sorted(artifacts)


def copy_structural_figures(output_dir: Path = config.OUTPUT_FIGURES_DIR) -> list[Path]:
    """Copy final structural figure images to standardized output names when present."""

    output_dir.mkdir(parents=True, exist_ok=True)
    copies: list[Path] = []
    mapping = {
        "figure_6_4_von_mises_stress.png": "fig_structural_von_mises_envelope.png",
        "figure_6_5_displacement_magnitude.png": "fig_structural_displacement_envelope.png",
    }
    for source_name, destination_name in mapping.items():
        source = config.FINAL_STRUCTURAL_DIR / source_name
        if source.exists():
            destination = output_dir / destination_name
            shutil.copy2(source, destination)
            copies.append(destination)
    return copies


def write_structural_report(output_path: Path) -> Path:
    """Write a concise report describing available structural-screening artifacts."""

    artifacts = discover_structural_artifacts()
    copied = copy_structural_figures()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Structural Screening Report",
        "",
        "Structural files in this repository support thesis screening and visualization.",
        "They should not be interpreted as certification-grade structural validation.",
        "",
        f"Selected artifact count: {len(artifacts)}",
        "",
    ]
    if copied:
        lines.append("## Clean Figure Copies")
        lines.extend(f"- `{path.relative_to(config.PROJECT_ROOT)}`" for path in copied)
        lines.append("")
    lines.extend(
        [
            "## Reproduction Notes",
            "",
            "- Historical Python and MATLAB structural scripts are preserved under `archive/legacy_scripts/`.",
            "- The clean Python wrapper reports available structural context but does not execute archived FEA scripts.",
            "- Native Abaqus files require Abaqus and are not regenerated by the clean Python workflow.",
            "",
        ]
    )
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return output_path
