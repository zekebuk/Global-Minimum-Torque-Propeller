"""OpenFOAM hover case: steady incompressible RANS with an MRF rotor zone.

Model (the shared blade frame: +z rotation axis and thrust, the rotor spins about +z):

- ``simpleFoam`` with k-omega SST and wall functions, ``nu = mu / rho`` from the design.
- MRF zone: a cylinder around the rotor plane rotating at +omega about +z.
- Box domain, longer below the rotor (-z, wake side). All far-field faces use total pressure
  p0 = 0 with ``pressureInletOutletVelocity``, the standard hover set-up in which the rotor
  entrains its own inflow.
- Mesh: blockMesh background, snappyHexMesh refined in the MRF zone and on the blade surface.
- Outputs: the ``forces`` function object (integrated thrust and torque), plus pressure and wall
  shear stress sampled on the blade surface. These are integrated here over the BEMT station strips
  by true radius r = sqrt(x^2 + y^2), so CFD and BEMT loading compare station by station.

Units are SI. OpenFOAM's incompressible pressure is kinematic (p / rho), so forces scale by rho.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import numpy as np

FOAM_HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by prandtl_prop.cfd.openfoam
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""


@dataclass(frozen=True)
class CaseParameters:
    radius_m: float
    omega_rad_s: float
    nu_m2_s: float
    rho_kg_m3: float
    blade_z_extent_m: tuple[float, float]
    side_factor: float = 3.0
    above_factor: float = 3.0
    below_factor: float = 6.0
    background_cells_per_radius: int = 4
    mrf_radius_factor: float = 1.08
    mrf_half_height_factor: float = 0.12
    mrf_refinement_level: int = 2
    surface_refinement_levels: tuple[int, int] = (5, 6)
    feature_refinement_level: int = 6
    iterations: int = 1000
    snapshots: int = 5
    processors: int = 1
    function_objects: bool = False


def _write(path: Path, cls: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(FOAM_HEADER.format(cls=cls, obj=path.name) + body, encoding="utf-8")


def write_case(case: Path, rotor_stl_m: Path, params: CaseParameters) -> Path:
    """Write a complete OpenFOAM case for a rotor STL given in metres."""

    case = Path(case)
    if case.exists():
        shutil.rmtree(case)
    (case / "constant" / "triSurface").mkdir(parents=True)
    shutil.copy2(rotor_stl_m, case / "constant" / "triSurface" / "blade.stl")

    R = params.radius_m
    side, above, below = params.side_factor * R, params.above_factor * R, params.below_factor * R
    cell = R / params.background_cells_per_radius
    nx = max(2, round(2 * side / cell))
    nz = max(2, round((above + below) / cell))
    mrf_r = params.mrf_radius_factor * R
    z_low, z_high = params.blade_z_extent_m
    mrf_h = max(params.mrf_half_height_factor * R, 1.5 * max(abs(z_low), abs(z_high)))
    s_min, s_max = params.surface_refinement_levels

    _write(
        case / "system" / "blockMeshDict",
        "dictionary",
        f"""
convertToMeters 1;
vertices
(
    ({-side} {-side} {-below}) ({side} {-side} {-below}) ({side} {side} {-below}) ({-side} {side} {-below})
    ({-side} {-side} {above}) ({side} {-side} {above}) ({side} {side} {above}) ({-side} {side} {above})
);
blocks ( hex (0 1 2 3 4 5 6 7) ({nx} {nx} {nz}) simpleGrading (1 1 1) );
edges ();
boundary
(
    farfield {{ type patch; faces ( (0 3 2 1) (4 5 6 7) (0 1 5 4) (1 2 6 5) (2 3 7 6) (3 0 4 7) ); }}
);
mergePatchPairs ();
""",
    )
    _write(
        case / "system" / "surfaceFeatureExtractDict",
        "dictionary",
        """
blade.stl
{
    extractionMethod    extractFromSurface;
    extractFromSurfaceCoeffs { includedAngle 150; }
    writeObj            no;
}
""",
    )
    location = (0.0123 * R, 0.0217 * R, above * 0.61)
    _write(
        case / "system" / "snappyHexMeshDict",
        "dictionary",
        f"""
castellatedMesh true;
snap            true;
addLayers       false;
geometry
{{
    blade.stl {{ type triSurfaceMesh; name blade; }}
    mrfRegion {{ type searchableCylinder; point1 (0 0 {-mrf_h}); point2 (0 0 {mrf_h}); radius {mrf_r}; }}
}}
castellatedMeshControls
{{
    maxLocalCells 4000000; maxGlobalCells 8000000; minRefinementCells 10; maxLoadUnbalance 0.10;
    nCellsBetweenLevels 3;
    features ( {{ file "blade.eMesh"; level {params.feature_refinement_level}; }} );
    refinementSurfaces {{ blade {{ level ({s_min} {s_max}); patchInfo {{ type wall; }} }} }}
    resolveFeatureAngle 30;
    refinementRegions {{ mrfRegion {{ mode inside; levels ((1e15 {params.mrf_refinement_level})); }} }}
    locationInMesh ({location[0]} {location[1]} {location[2]});
    allowFreeStandingZoneFaces true;
}}
snapControls {{ nSmoothPatch 3; tolerance 2.0; nSolveIter 50; nRelaxIter 5; nFeatureSnapIter 10;
    implicitFeatureSnap false; explicitFeatureSnap true; multiRegionFeatureSnap false; }}
addLayersControls {{ relativeSizes true; layers {{ }}; expansionRatio 1.2; finalLayerThickness 0.5; minThickness 0.1;
    nGrow 0; featureAngle 60; nRelaxIter 3; nSmoothSurfaceNormals 1; nSmoothNormals 3; nSmoothThickness 10;
    maxFaceThicknessRatio 0.5; maxThicknessToMedialRatio 0.3; minMedialAxisAngle 90; nBufferCellsNoExtrude 0; nLayerIter 50; }}
meshQualityControls
{{
    maxNonOrtho 65; maxBoundarySkewness 20; maxInternalSkewness 4; maxConcave 80; minVol 1e-13;
    minTetQuality 1e-15; minArea -1; minTwist 0.02; minDeterminant 0.001; minFaceWeight 0.05;
    minVolRatio 0.01; minTriangleTwist -1; nSmoothScale 4; errorReduction 0.75;
    relaxed {{ maxNonOrtho 75; }}
}}
mergeTolerance 1e-6;
""",
    )
    _write(
        case / "system" / "topoSetDict",
        "dictionary",
        f"""
actions
(
    {{ name rotor; type cellSet; action new; source cylinderToCell;
       sourceInfo {{ p1 (0 0 {-mrf_h}); p2 (0 0 {mrf_h}); radius {mrf_r}; }} }}
    {{ name rotor; type cellZoneSet; action new; source setToCellZone; sourceInfo {{ set rotor; }} }}
);
""",
    )
    _write(
        case / "constant" / "MRFProperties",
        "dictionary",
        f"""
rotor
{{
    cellZone    rotor;
    active      yes;
    nonRotatingPatches ();
    origin      (0 0 0);
    axis        (0 0 1);
    omega       {params.omega_rad_s:.10g};
}}
""",
    )
    _write(case / "constant" / "transportProperties", "dictionary", f"\ntransportModel Newtonian;\nnu {params.nu_m2_s:.10g};\n")
    _write(
        case / "constant" / "turbulenceProperties",
        "dictionary",
        "\nsimulationType RAS;\nRAS { RASModel kOmegaSST; turbulence on; printCoeffs on; }\n",
    )
    function_block = (
        f"""functions
{{
    forces
    {{
        type forces; libs ("libforces.so"); writeControl timeStep; writeInterval 1;
        patches (blade); rho rhoInf; rhoInf {params.rho_kg_m3}; CofR (0 0 0); log true;
    }}
    yPlus {{ type yPlus; libs ("libfieldFunctionObjects.so"); writeControl writeTime; }}
}}"""
        if params.function_objects
        else "functions {}"
    )
    _write(
        case / "system" / "controlDict",
        "dictionary",
        f"""
application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {params.iterations};
deltaT          1;
writeControl    timeStep;
writeInterval   {max(1, params.iterations // max(1, params.snapshots))};
purgeWrite      0;
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;
{function_block}
""",
    )
    _write(
        case / "system" / "fvSchemes",
        "dictionary",
        """
ddtSchemes { default steadyState; }
gradSchemes { default Gauss linear; grad(U) cellLimited Gauss linear 1; }
divSchemes
{
    default none;
    div(phi,U) bounded Gauss linearUpwind grad(U);
    div(phi,k) bounded Gauss upwind;
    div(phi,omega) bounded Gauss upwind;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear limited corrected 0.5; }
interpolationSchemes { default linear; }
snGradSchemes { default limited corrected 0.5; }
wallDist { method meshWave; }
""",
    )
    _write(
        case / "system" / "fvSolution",
        "dictionary",
        """
solvers
{
    p { solver GAMG; smoother GaussSeidel; tolerance 1e-7; relTol 0.05; }
    "(U|k|omega)" { solver smoothSolver; smoother symGaussSeidel; tolerance 1e-8; relTol 0.1; }
}
SIMPLE
{
    nNonOrthogonalCorrectors 1;
    consistent no;
    residualControl { p 1e-5; U 1e-6; "(k|omega)" 1e-6; }
}
relaxationFactors { fields { p 0.3; } equations { U 0.7; "(k|omega)" 0.7; } }
""",
    )
    nx_p, ny_p, nz_p = _processor_grid(max(1, params.processors))
    _write(
        case / "system" / "decomposeParDict",
        "dictionary",
        f"\nnumberOfSubdomains {nx_p * ny_p * nz_p};\nmethod hierarchical;\n"
        f"hierarchicalCoeffs {{ n ({nx_p} {ny_p} {nz_p}); delta 0.001; order xyz; }}\n",
    )

    k0, omega0 = 1.0e-4, 10.0
    fields = {
        "U": (
            "volVectorField",
            "[0 1 -1 0 0 0 0]",
            "uniform (0 0 0)",
            "farfield { type pressureInletOutletVelocity; value uniform (0 0 0); }\n    blade { type fixedValue; value uniform (0 0 0); }",
        ),
        "p": (
            "volScalarField",
            "[0 2 -2 0 0 0 0]",
            "uniform 0",
            "farfield { type totalPressure; p0 uniform 0; value uniform 0; }\n    blade { type zeroGradient; }",
        ),
        "k": (
            "volScalarField",
            "[0 2 -2 0 0 0 0]",
            f"uniform {k0}",
            f"farfield {{ type inletOutlet; inletValue uniform {k0}; value uniform {k0}; }}\n    blade {{ type kqRWallFunction; value uniform {k0}; }}",
        ),
        "omega": (
            "volScalarField",
            "[0 0 -1 0 0 0 0]",
            f"uniform {omega0}",
            f"farfield {{ type inletOutlet; inletValue uniform {omega0}; value uniform {omega0}; }}\n    blade {{ type omegaWallFunction; value uniform {omega0}; }}",
        ),
        "nut": (
            "volScalarField",
            "[0 2 -1 0 0 0 0]",
            "uniform 0",
            "farfield { type calculated; value uniform 0; }\n    blade { type nutkWallFunction; value uniform 0; }",
        ),
    }
    for name, (cls, dims, internal, boundary) in fields.items():
        _write(case / "0" / name, cls, f"\ndimensions {dims};\ninternalField {internal};\nboundaryField\n{{\n    {boundary}\n}}\n")
    return case


def _processor_grid(count: int) -> tuple[int, int, int]:
    """Split ``count`` into (nx, ny, nz) factors; hierarchical decomposition ships with every OpenFOAM build."""

    factors: list[int] = []
    remaining = count
    for prime in (2, 3, 5, 7):
        while remaining % prime == 0:
            factors.append(prime)
            remaining //= prime
    if remaining > 1:
        factors.append(remaining)
    grid = [1, 1, 1]
    for factor in sorted(factors, reverse=True):
        grid[grid.index(min(grid))] *= factor
    return grid[0], grid[1], grid[2]


def run_case(case: Path, *, processors: int = 1, bashrc: str | None = None, timeout_s: int = 6 * 3600) -> Path:
    """Mesh and solve the case. Writes ``log.<step>`` files; raises with the failing step's log tail."""

    bashrc = bashrc or _default_bashrc()
    steps = [
        ("blockMesh", "blockMesh"),
        ("surfaceFeatureExtract", "surfaceFeatureExtract"),
        ("snappyHexMesh", "snappyHexMesh -overwrite"),
        ("topoSet", "topoSet"),
        ("checkMesh", "checkMesh"),
    ]
    if processors > 1:
        steps += [
            ("decomposePar", "decomposePar -force"),
            ("simpleFoam", f"mpirun --allow-run-as-root --oversubscribe -np {processors} simpleFoam -parallel"),
            ("reconstructPar", "reconstructPar"),
        ]
    else:
        steps.append(("simpleFoam", "simpleFoam"))
    for name, command in steps:
        log = case / f"log.{name}"
        script = f"source {bashrc} >/dev/null 2>&1 || true; cd '{case}' && {command}"
        with log.open("w", encoding="utf-8") as handle:
            completed = subprocess.run(
                ["bash", "-c", script], stdout=handle, stderr=subprocess.STDOUT, timeout=timeout_s, check=False, env=dict(os.environ)
            )
        text = log.read_text(encoding="utf-8", errors="replace")
        failed = completed.returncode != 0 or "FOAM FATAL" in text
        if name == "checkMesh" and "Failed" in text and "mesh checks" in text:
            failed = False  # snappy meshes often fail strict checks yet run; checkMesh output is kept for review
        if failed:
            raise RuntimeError(
                f"OpenFOAM step {name} failed (exit {completed.returncode}); last lines:\n" + "\n".join(text.splitlines()[-25:])
            )
    return case


def _default_bashrc() -> str:
    for candidate in ("/usr/share/openfoam/etc/bashrc", "/usr/lib/openfoam/openfoam/etc/bashrc", "/opt/openfoam/etc/bashrc"):
        if Path(candidate).is_file():
            return candidate
    return os.environ.get("FOAM_BASHRC", "/usr/share/openfoam/etc/bashrc")


# ------------------------------------------------------------------------------- post-processing
#
# Loads are computed from the written fields, not from function objects. This works on any OpenFOAM
# build (some distribution builds, e.g. Ubuntu's v1912, crash in every function object), and it is
# checked against an independent axial momentum balance over the far-field boundary.


@dataclass(frozen=True)
class PolyMesh:
    points: np.ndarray
    faces: list[np.ndarray]
    owner: np.ndarray
    neighbour: np.ndarray
    patches: dict[str, tuple[int, int]]  # name -> (start face, face count)

    def patch_faces(self, name: str) -> range:
        start, count = self.patches[name]
        return range(start, start + count)


def read_mesh(case: Path) -> PolyMesh:
    mesh = Path(case) / "constant" / "polyMesh"
    points = _numbers(_list_text(mesh / "points")).reshape(-1, 3)
    faces = [np.array(item.split(), dtype=np.int64) for item in re.findall(r"\d+\(([^()]*)\)", _list_text(mesh / "faces"))]
    owner = _numbers(_list_text(mesh / "owner")).astype(np.int64)
    neighbour = _numbers(_list_text(mesh / "neighbour")).astype(np.int64)
    boundary = _strip_comments((mesh / "boundary").read_text(encoding="utf-8"))
    patches = {
        match[1]: (int(match[3]), int(match[2]))
        for match in re.finditer(r"(\w+)\s*\{[^{}]*?nFaces\s+(\d+);[^{}]*?startFace\s+(\d+);", boundary, re.S)
    }
    return PolyMesh(points, faces, owner, neighbour, patches)


def face_geometry(mesh: PolyMesh, face_ids: Sequence[int]) -> tuple[np.ndarray, np.ndarray]:
    """Face centroids and area vectors (OpenFOAM orientation: out of the owner cell, i.e. out of the fluid)."""

    centres = np.zeros((len(face_ids), 3))
    areas = np.zeros((len(face_ids), 3))
    for row, face_id in enumerate(face_ids):
        vertices = mesh.points[mesh.faces[face_id]]
        middle = vertices.mean(axis=0)
        following = np.roll(vertices, -1, axis=0)
        triangles = 0.5 * np.cross(vertices - middle, following - middle)
        magnitudes = np.linalg.norm(triangles, axis=1)
        areas[row] = triangles.sum(axis=0)
        centres[row] = ((vertices + following + middle) / 3.0 * magnitudes[:, None]).sum(axis=0) / max(magnitudes.sum(), 1.0e-300)
    return centres, areas


def cell_centres(mesh: PolyMesh, cells: np.ndarray) -> np.ndarray:
    """Approximate centres (mean of unique vertices) for the requested cells; repeats are allowed."""

    unique, inverse = np.unique(np.asarray(cells, dtype=np.int64), return_inverse=True)
    position = {int(cell): index for index, cell in enumerate(unique)}
    vertex_sets: list[set[int]] = [set() for _ in unique]
    for cell_array in (mesh.owner, mesh.neighbour):
        hits = np.flatnonzero(np.isin(cell_array, unique))
        for face_id in hits:
            vertex_sets[position[int(cell_array[face_id])]].update(mesh.faces[face_id].tolist())
    centres = np.array([mesh.points[sorted(vertices)].mean(axis=0) for vertices in vertex_sets])
    return centres[inverse]


@dataclass(frozen=True)
class FoamField:
    internal: np.ndarray
    boundary: dict[str, np.ndarray | None]  # patch -> face values (None when the patch writes no value)


def read_field(path: Path, components: int) -> FoamField:
    """Read an ASCII volScalarField (components=1) or volVectorField (components=3)."""

    text = _strip_comments(Path(path).read_text(encoding="utf-8"))
    internal = _field_values(text[text.index("internalField") :], components)
    boundary: dict[str, np.ndarray | None] = {}
    body = text[text.index("boundaryField") :]
    for match in re.finditer(r"\n\s{4}(\w+)\s*\n\s*\{(.*?)\n\s{4}\}", body, re.S):
        block = match[2]
        value_at = re.search(r"\bvalue\s+", block)
        boundary[match[1]] = _field_values(block[value_at.start() :], components) if value_at else None
    return FoamField(internal, boundary)


def latest_time(case: Path) -> Path:
    times = [path for path in Path(case).iterdir() if path.is_dir() and _is_number(path.name) and float(path.name) > 0]
    if not times:
        raise FileNotFoundError(f"No solution time directories in {case}")
    return max(times, key=lambda path: float(path.name))


def solution_times(case: Path) -> list[Path]:
    return sorted(
        (path for path in Path(case).iterdir() if path.is_dir() and _is_number(path.name) and float(path.name) > 0),
        key=lambda p: float(p.name),
    )


@dataclass(frozen=True)
class WallLoads:
    centres: np.ndarray  # (n, 3) face centroids
    force_N: np.ndarray  # (n, 3) force of the fluid on each wall face (pressure + viscous)
    pressure_force_N: np.ndarray
    viscous_force_N: np.ndarray


def wall_loads(
    case: Path, time_dir: Path, *, rho_kg_m3: float, nu_m2_s: float, patch: str = "blade", mesh: PolyMesh | None = None
) -> WallLoads:
    """Force of the fluid on each wall face.

    Pressure: on a zeroGradient wall the face pressure equals the owner-cell value, so
    F_p = rho p S, where S points out of the fluid, into the blade. Viscous: the wall-function
    shear rho nu_eff (U_P - U_w)_t / delta, with nu_eff = nu + nut on the face and delta the
    wall-normal distance from the cell centre. This is the same approximation OpenFOAM's
    wallShearStress uses.
    """

    mesh = mesh or read_mesh(case)
    face_ids = mesh.patch_faces(patch)
    owners = mesh.owner[list(face_ids)]
    centres, areas = face_geometry(mesh, face_ids)
    magnitude = np.linalg.norm(areas, axis=1)
    normal = areas / magnitude[:, None]
    p = read_field(time_dir / "p", 1)
    U = read_field(time_dir / "U", 3)
    nut = read_field(time_dir / "nut", 1)
    pressure = p.boundary.get(patch)
    pressure = p.internal[owners] if pressure is None else pressure
    wall_velocity = U.boundary[patch] if U.boundary.get(patch) is not None else np.zeros((len(owners), 3))
    nut_face = nut.boundary[patch] if nut.boundary.get(patch) is not None else nut.internal[owners]
    delta = np.abs(((centres - cell_centres(mesh, owners)) * normal).sum(axis=1))
    relative = U.internal[owners] - wall_velocity
    tangential = relative - (relative * normal).sum(axis=1)[:, None] * normal
    pressure_force = rho_kg_m3 * np.asarray(pressure).reshape(-1)[:, None] * areas
    viscous_force = rho_kg_m3 * ((nu_m2_s + nut_face) / np.maximum(delta, 1.0e-12))[:, None] * tangential * magnitude[:, None]
    return WallLoads(centres, pressure_force + viscous_force, pressure_force, viscous_force)


def farfield_thrust(
    case: Path, time_dir: Path, *, rho_kg_m3: float, patch: str = "farfield", mesh: PolyMesh | None = None
) -> dict[str, float]:
    """Thrust from the axial momentum balance over the far field (independent of wall loads).

    Steady state, fluid control volume: the force of the blades on the fluid equals
    integral(rho (U_z (U.n) + p n_z)) over the far field, with n outward. The MRF source
    Omega x U has no z component, so the balance is exact up to far-field viscous stress.
    Rotor thrust is the negative of the force on the fluid.
    """

    mesh = mesh or read_mesh(case)
    face_ids = mesh.patch_faces(patch)
    _, areas = face_geometry(mesh, face_ids)
    p = read_field(time_dir / "p", 1).boundary[patch]
    U = read_field(time_dir / "U", 3).boundary[patch]
    flux = (U * areas).sum(axis=1)
    momentum_z = rho_kg_m3 * (U[:, 2] * flux + np.asarray(p).reshape(-1) * areas[:, 2])
    return {"thrust_N": float(-momentum_z.sum()), "net_volume_flux_m3_s": float(flux.sum()), "outflow_m3_s": float(flux[flux > 0].sum())}


def station_loads(loads: WallLoads, station_r_m: Sequence[float]) -> tuple[np.ndarray, np.ndarray]:
    """Per-station thrust dT (N) and shaft torque dQ (N*m), summed over all blades, binned by r = sqrt(x^2 + y^2)."""

    radius = np.hypot(loads.centres[:, 0], loads.centres[:, 1])
    radii = np.asarray(station_r_m, dtype=float)
    edges = np.concatenate([[0.0], 0.5 * (radii[1:] + radii[:-1]), [np.inf]])
    strip = np.clip(np.searchsorted(edges, radius, side="right") - 1, 0, len(radii) - 1)
    # Torque the fluid applies about +z opposes rotation; the shaft must supply its negative.
    shaft = -(loads.centres[:, 0] * loads.force_N[:, 1] - loads.centres[:, 1] * loads.force_N[:, 0])
    return (
        np.bincount(strip, weights=loads.force_N[:, 2], minlength=len(radii)),
        np.bincount(strip, weights=shaft, minlength=len(radii)),
    )


def residual_history(case: Path) -> dict[str, list[float]]:
    """Initial residuals per iteration from ``log.simpleFoam``."""

    history: dict[str, list[float]] = {}
    log = Path(case) / "log.simpleFoam"
    if not log.is_file():
        return history
    for match in re.finditer(r"Solving for (\w+), Initial residual = ([-+\deE.]+)", log.read_text(encoding="utf-8", errors="replace")):
        history.setdefault(match[1], []).append(float(match[2]))
    return history


def _is_number(text: str) -> bool:
    try:
        float(text)
    except ValueError:
        return False
    return True


def _strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def _list_text(path: Path) -> str:
    text = _strip_comments(Path(path).read_text(encoding="utf-8"))
    if "FoamFile" in text:
        text = text[text.index("}", text.index("FoamFile")) + 1 :]
    match = re.search(r"(\d+)\s*\(", text)
    if match is None:
        raise ValueError(f"No list found in {path}")
    return text[match.end() : text.rindex(")")]


def _numbers(text: str) -> np.ndarray:
    return np.array(text.replace("(", " ").replace(")", " ").split(), dtype=float)


def _field_values(text: str, components: int) -> np.ndarray:
    head = re.match(r"\w+\s+(uniform|nonuniform)\s*", text)
    if head is None:
        raise ValueError("Unrecognised field entry")
    rest = text[head.end() :]
    if head[1] == "uniform":
        value = _numbers(rest[: rest.index(";")])
        return value.reshape(1, -1) if components > 1 else value
    count_match = re.match(r"List<\w+>\s*(\d+)\s*\(", rest)
    if count_match is None:
        raise ValueError("Unrecognised nonuniform list")
    count = int(count_match[1])
    body = rest[count_match.end() :]
    closing = re.search(r"\n\s*\)", body)  # long lists: one entry per line, ')' alone closes the list
    if closing is not None and count > 10:
        end = closing.start()
    else:  # short lists are written inline, e.g. 3((0 0 1) (0 1 0) (1 0 0))
        depth, end = 1, len(body)
        for position, char in enumerate(body):
            depth += char == "("
            depth -= char == ")"
            if depth == 0:
                end = position
                break
    values = _numbers(body[:end])
    return values.reshape(count, components) if components > 1 else values.reshape(count)


def blade_z_extent(stl_path: Path) -> tuple[float, float]:
    """Axial extent of an STL (ASCII or binary) in its own units."""

    data = Path(stl_path).read_bytes()
    if data[:5].lower() == b"solid" and b"facet" in data[:1024]:
        z = [float(match) for match in re.findall(rb"vertex\s+\S+\s+\S+\s+(\S+)", data)]
    else:
        count = int.from_bytes(data[80:84], "little")
        records = np.frombuffer(data[84 : 84 + 50 * count], dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]))
        z = records["v"][:, :, 2].ravel().tolist()
    return float(min(z)), float(max(z))
