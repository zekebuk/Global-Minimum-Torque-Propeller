"""Write the production documents: assembly line plan, supplier list, equipment budget, layout."""

from __future__ import annotations

import csv
from pathlib import Path

from bldc_motor.production import assembly_line as al
from bldc_motor.production import suppliers as sp


def _money(x: float) -> str:
    return f"${x:,.0f}" if x >= 100 else f"${x:,.2f}"


def write_equipment_csv(path: Path) -> Path:
    with path.open("w", newline="", encoding="utf-8") as handle:
        w = csv.writer(handle)
        w.writerow(["key", "item", "station", "qty", "unit_usd", "total_usd", "vendor", "url", "price_status", "notes"])
        for e in al.EQUIPMENT:
            w.writerow(
                [
                    e.key,
                    e.item,
                    e.station,
                    e.qty,
                    f"{e.price_usd:.2f}",
                    f"{e.total:.2f}",
                    e.vendor,
                    e.url,
                    e.status,
                    e.notes,
                ]
            )
    return path


def suppliers_markdown() -> str:
    lines = [
        "# Supplier candidates",
        "",
        f"Researched {sp.SEEN} from supplier and retailer pages plus search results. **Nothing here is a quote.** "
        "Status `snippet` = taken from a search snippet of the page (verify), `listing` = marketplace range, `quote` = no public price. "
        "Qualify every supplier with samples and first-article inspection against the drawings in `rl2407/drawings/`.",
        "",
    ]
    for category, items in sp.by_category().items():
        lines += [
            f"## {category.capitalize()}",
            "",
            "| Supplier | Offer | Indicative price | Status | Notes |",
            "| --- | --- | --- | --- | --- |",
        ]
        for s in items:
            lines.append(f"| [{s.name}]({s.url}) | {s.offer} | {s.price} | {s.status} | {s.notes} |")
        lines.append("")
    lines += ["## Open RFQs (send with DXF/STEP/PDF from `rl2407/`)", ""]
    lines += [f"{i}. {q}" for i, q in enumerate(sp.RFQ_QUESTIONS, start=1)]
    lines += [
        "",
        "Key part facts confirmed during research: the 4x9x4 bearing is **684ZZ** (NMB designation L-940ZZ). MR84ZZ is 4x8x3 and does NOT fit. "
        "The e-clip for the Ø4 shaft is **DIN 6799 size 3.2** (groove Ø3.2 h11 x 0.64 mm, 0.6 mm ring); size 4 is for 5-7 mm shafts.",
    ]
    return "\n".join(lines) + "\n"


def plan_markdown(volume: float = 5000.0) -> str:
    p = al.plan(volume)
    p_cnc = al.plan(volume, cnc_winder_min=3.0)
    lines = [
        "# RL2407 assembly line plan (capital < $15k)",
        "",
        "Generated by `bldc-motor production plan` from `bldc_motor.production.assembly_line`. The equipment prices come from the "
        f"{sp.SEEN} research (status per line in `equipment_budget.csv`), and the cycle times are **engineering estimates to replace with "
        "a time study during the 50-piece pilot.** The labour rate is an assumption (${:.0f}/h fully loaded).".format(
            al.LABOUR_RATE_USD_H
        ),
        "",
        "## Strategy: buy precision, make labour + test",
        "",
        "| Make in-house (this line) | Buy (outsourced, from drawings) |",
        "| --- | --- |",
        "| Winding, termination, impregnation | Bonded + epoxy-coated stator stacks (DWG-001/002) |",
        "| Base and rotor subassembly (press, bond) | Pre-magnetised arc magnets, -01/-02 matched sets (DWG-004) |",
        "| Rotor balancing | CNC bell, base, ring (DWG-005/006/007), anodised |",
        "| Final assembly, 100 % end-of-line test, 1-in-50 loaded test | Shaft (DWG-008), 684ZZ bearings, e-clips, grubs |",
        "",
        "Automatic outrunner needle winders were all found **above the entire budget** ($15-16k QIWEI, $18k Rimy, $25k+ NIDE "
        "listings; Vacuz quotes 90-150k RMB). This design was chosen partly for winding simplicity: 6 turns per tooth, "
        "single-strand AWG23, slot fill 0.38 and a 2.5 mm needle opening. That makes jig-indexed hand winding realistic, and an "
        "open-source CNC winder is budgeted as phase 2.",
        "",
        "## Process flow",
        "",
        "```mermaid",
        "flowchart LR",
        "    GI[S1 Goods-in<br/>AQL sampling] --> SP[S2 Stator prep]",
        "    SP --> W[S3 Winding<br/>bottleneck] --> T[S4 Termination] --> E1[S5 R + hipot]",
        "    E1 --> V[S6 Varnish + cure]",
        "    V --> B[S7 Base subassy<br/>bearings + stator]",
        "    GI --> R[S8 Rotor subassy<br/>magnets, ring, shaft] --> BAL[S9 Balance]",
        "    B --> F[S10 Final assy + EOL test]",
        "    BAL --> F --> P[S11 Label + pack]",
        "```",
        "",
        "## Stations",
        "",
        "| Station | Labour min/motor | Equipment | Fixtures (3D-printed / turned) | Checks | Cure / soak |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    eq = {e.key: e.item.split(" (")[0] for e in al.EQUIPMENT}
    for s in al.STATIONS:
        lines.append(
            f"| **{s.key}** {s.name} | {s.labour_min:.1f} | {'; '.join(eq[k] for k in s.equipment) or '-'} | {'; '.join(s.fixtures)} | "
            f"{'; '.join(s.checks)} | {f'{s.batch_wait_h:g} h batch' if s.batch_wait_h else '-'} |"
        )
    lines += [
        "",
        f"**Total labour: {p.labour_min_per_motor:.1f} min per motor.** Bottleneck: {p.bottleneck}.",
        "",
        "## Capital budget",
        "",
        "| Item | Station | Qty | Total | Price status |",
        "| --- | --- | --- | --- | --- |",
    ]
    for e in sorted(al.EQUIPMENT, key=lambda e: -e.total):
        name = f"[{e.item}]({e.url})" if e.url else e.item
        lines.append(f"| {name} | {e.station} | {e.qty} | {_money(e.total)} | {e.status} |")
    lines += [
        f"| **Equipment subtotal** | | | **{_money(p.equipment_total)}** | |",
        f"| Contingency {al.CONTINGENCY:.0%} | | | {_money(p.contingency)} | |",
        f"| **Total capital** | | | **{_money(p.capital_total)}** | {'within' if p.within_budget else 'OVER'} ${al.BUDGET_USD:,.0f} (margin {_money(al.BUDGET_USD - p.capital_total)}) |",
        "",
        "Biggest capital risks: (1) the Tyto 1585 stand was **sold out** on the research date (an alternative loaded-test rig eats into "
        "contingency); (2) the Balanset-1A plus home-made spindle is not proven on a 17 g bell (the fallback UAV balancer listing is $3.8-5.2k, "
        "which is above the remaining margin). Run the balancer and spindle trial first, before buying anything else.",
        "",
        "Deferred upgrades (not in the budget):",
        "",
    ]
    lines += [f"- {name}: {price}, {when}" for name, price, when in al.UPGRADES]
    lines += [
        "",
        "## Capacity (single shift, 7 productive h/day, 230 days/yr)",
        "",
        "| Operators | Hand winding (motors/yr) | With CNC winder at 3 min (motors/yr) |",
        "| --- | --- | --- |",
    ]
    for n in (1, 2, 3):
        lines.append(f"| {n} | {p.capacity_per_year_single_shift[n]:,} | {p_cnc.capacity_per_year_single_shift[n]:,} |")
    lines += [
        "",
        f"One operator builds about {p.motors_per_operator_day:.0f} motors per day. Shared equipment is far from saturated at these rates "
        "(balancing 4 min/rotor, about 100 rotors/day; the oven batches 12 stators per 3 h cure), so the line scales by adding operators "
        "and winding seats.",
        "",
        "## Unit cost",
        "",
        "| Basis | BOM | Labour | Scrap | Capital amortisation (3 yr) | **Total / motor** |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for label, u in p.unit_cost.items():
        lines.append(
            f"| {label} | {_money(u['bom_usd'])} | {_money(u['labour_usd'])} | {_money(u['scrap_usd'])} | {_money(u['capital_amortisation_usd'])} | **{_money(u['total_usd'])}** |"
        )
    lines += [
        "",
        "BOM lines and their basis (pilot / volume):",
        "",
        "| Part | Pilot (50) | Volume | Basis |",
        "| --- | --- | --- | --- |",
    ]
    for part, (pilot, vol, basis) in al.BOM.items():
        lines.append(f"| {part} | {_money(pilot)} | {_money(vol)} | {basis} |")
    lines += [
        "",
        f"At volume, labour (${p.unit_cost[list(p.unit_cost)[1]]['labour_usd']:.2f} at ${al.LABOUR_RATE_USD_H:.0f}/h) is the largest cost line, so the "
        f"CNC winder (S3 10 -> 3 min) is worth about ${(p.unit_cost[list(p.unit_cost)[1]]['total_usd'] - p_cnc.unit_cost[list(p_cnc.unit_cost)[1]]['total_usd']):.2f}/motor. "
        "Most BOM values are estimates until the RFQs in `suppliers.md` come back. Treat the pilot figures as planning numbers, not quotes.",
        "",
        "## Ramp plan",
        "",
        "| Phase | Output | Goal | Exit criteria |",
        "| --- | --- | --- | --- |",
        "| P0 Prototype | 5-10 motors | Validate drawings, fits, model | Bench fit (`bldc-motor fit`) within spec_sheet acceptance limits; `design calibrate` run |",
        "| P1 Pilot | 50 motors | Time study, fixture refinement, first-pass yield | FPY >= 90 %, cycle time measured, PFMEA updated |",
        "| P2 Low-rate | 100-200/month | Supplier volume pricing, CNC winder online | Cpk >= 1.33 on Kv and R_ll; supplier PPAP-lite |",
        "| P3 | 400+/month | 2-3 operators | Re-quote automatic winder if > ~6k/yr |",
        "",
        "## Quality plan (critical characteristics)",
        "",
        "| Characteristic | Spec | Where checked | Method | Frequency |",
        "| --- | --- | --- | --- | --- |",
        "| Stator bore / tube OD clearance | 0.02-0.09 mm | S1 | Go/no-go pins | AQL 1.0 |",
        "| Bearing bore Ø9 H6 | 0 / +0.009 | S1 | Bore gauge / go-no-go | AQL 1.0 |",
        "| Magnet thickness / pole marking | 1.70 ±0.02, -01/-02 | S1 | Micrometer, gaussmeter | AQL 1.0 per lot |",
        "| Turns, direction | 6/tooth per DWG-003 | S3 | Jig counter + R balance | 100 % |",
        "| R line-line | 87.7 mΩ ±6 %, imbalance <= 2 % | S5, S10 | 4-wire, temp-corrected | 100 % |",
        "| Insulation | 1.05 kV AC 1 s <= 1 mA | S5, S10 | Hipot | 100 % |",
        "| Pole order | Alternating N/S | S8 | Gaussmeter / compass | 100 % |",
        "| Residual unbalance | <= 11 mg·mm | S9 | Balanset | 100 % |",
        "| Axial play | 0.02-0.08 mm | S10 | Dial indicator | 100 % |",
        "| Kv (no-load, 12 V) | 1687 rpm/V ±3 % | S10 | PSU + tach | 100 % |",
        "| Loaded performance | Within ±5 % of predicted curve | S10 | Tyto 1585 sweep | 1 in 50 |",
        "",
        "## Safety",
        "",
        "- **Magnets:** N52 arcs pinch and shatter. Keep them in a separate magnet zone at least 1.5 m from winding, use non-magnetic "
        "tools and spacers, and wear eye protection.",
        "- **Hipot:** interlocked fixture or two-hand operation, and post a warning sign.",
        "- **Varnish and oven:** solvent vapour, so vent outside. Follow the varnish SDS, and keep the cure-temperature log.",
        "- **Loaded test:** run props only inside the mesh cage, with an E-stop and a LiPo charging bag/box.",
        "",
        "## Floor layout",
        "",
        "![layout](line_layout.svg)",
        "",
        "A 6 × 4.5 m U-cell; material flows clockwise from stores to pack.",
    ]
    return "\n".join(lines) + "\n"


def write_all(out_dir: str | Path) -> dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "plan": out / "assembly_line_plan.md",
        "suppliers": out / "suppliers.md",
        "equipment_csv": out / "equipment_budget.csv",
        "layout": out / "line_layout.svg",
    }
    files["plan"].write_text(plan_markdown(), encoding="utf-8")
    files["suppliers"].write_text(suppliers_markdown(), encoding="utf-8")
    write_equipment_csv(files["equipment_csv"])
    files["layout"].write_text(al.layout_svg(), encoding="utf-8")
    return files
