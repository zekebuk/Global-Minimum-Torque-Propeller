function [summary_lines,summary_table] = meshSummaryForStation(station)
%MESHSUMMARYFORSTATION Metadata summary for ribbon/beam mesh plots.
%
% The mesh view is geometry, not a scalar result field, so this function
% intentionally reports mesh metadata instead of max/min plotted values.

num_stations = station.n;
num_nodes = 2*num_stations;
num_elements = max(num_stations - 1,0);

r_over_R_min = min(station.mu,[],'omitnan');
r_over_R_max = max(station.mu,[],'omitnan');
r_min_m = min(station.r,[],'omitnan');
r_max_m = max(station.r,[],'omitnan');
chord_min_m = min(station.chord,[],'omitnan');
chord_max_m = max(station.chord,[],'omitnan');

summary_lines = { ...
    'Mesh metadata', ...
    sprintf('Stations: %d',num_stations), ...
    sprintf('Nodes: %d',num_nodes), ...
    sprintf('Elements: %d',num_elements), ...
    sprintf('r/R range: %.6g to %.6g',r_over_R_min,r_over_R_max), ...
    sprintf('Radial coordinate range: %.6g to %.6g m',r_min_m,r_max_m), ...
    sprintf('Chord range: %.6g to %.6g m',chord_min_m,chord_max_m)};

summary_table = table(num_stations,num_nodes,num_elements, ...
    r_over_R_min,r_over_R_max,r_min_m,r_max_m,chord_min_m,chord_max_m, ...
    'VariableNames',{'num_stations','num_nodes','num_elements', ...
    'r_over_R_min','r_over_R_max','r_m_min','r_m_max', ...
    'chord_m_min','chord_m_max'});

end
