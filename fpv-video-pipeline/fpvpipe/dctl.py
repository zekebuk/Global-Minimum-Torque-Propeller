"""The scene-order grade's nodes 2, 3 and 5 as DCTLs with sliders, so every solved value is editable in Resolve.

A node loaded from a .cube is a black box; a node loaded from a .dctl shows its DEFINE_UI_PARAMS as sliders in the
Inspector (Color page > OpenFX panel > DCTL). Each function returns the DCTL source for one node with the solved
values baked in as the slider defaults, porting the numpy maths in grade5 line for line:

    node 2  LogPrimary.shadow (the shadow-only lift, which no CDL can hold) then LogToneSat.apply
    node 3  LogLook.apply (vibrance)
    node 5  Unify.apply (the reel-wide match)

Nodes 2 and 3 key their qualifiers on the *displayed* colour, i.e. the log pixel pushed through the CST: that is the
`key_cube` (the same conversion .cube node 4 uses), which DEFINE_LUT reads from the DCTL's own folder.
"""
from __future__ import annotations

from dataclasses import dataclass

KR, KB = 0.2126, 0.0722
KG = 1 - KR - KB

_HEADER = """// generated by fpvpipe/dctl.py - the sliders are the solved values; move them freely, the cut list is unchanged
"""

_CONST = {"FPV_PI": "3.14159265358979f", "FPV_STOP": "0.11569f"}   # one stop in GP-Log codes: ln(2) / ln(400)

_HELPERS = """

__DEVICE__ float fpv_clamp01(float x) { return _clampf(x, 0.0f, 1.0f); }
__DEVICE__ float fpv_wrap180(float h) { float x = _fmod(h + 180.0f, 360.0f); if (x < 0.0f) x += 360.0f; return x - 180.0f; }
__DEVICE__ float fpv_luma(float3 c) { return %(KR).6ff * c.x + %(KG).6ff * c.y + %(KB).6ff * c.z; }
__DEVICE__ float3 fpv_from_ycc(float y, float cb, float cr) {
    float r = y + 1.5748f * cr, b = y + 1.8556f * cb;
    return make_float3(r, (y - %(KR).6ff * r - %(KB).6ff * b) / %(KG).6ff, b);
}
__DEVICE__ float3 fpv_clamp3(float3 c) { return make_float3(fpv_clamp01(c.x), fpv_clamp01(c.y), fpv_clamp01(c.z)); }
__DEVICE__ float3 fpv_max3(float3 c, float m) { return make_float3(_fmaxf(c.x, m), _fmaxf(c.y, m), _fmaxf(c.z, m)); }
// float3 <op> float is not portable across DCTL back ends: spell it out.
__DEVICE__ float3 fpv_addf(float3 vv, float kk) { return make_float3(vv.x + kk, vv.y + kk, vv.z + kk); }
__DEVICE__ float3 fpv_mulf(float3 vv, float kk) { return make_float3(vv.x * kk, vv.y * kk, vv.z * kk); }
__DEVICE__ float3 fpv_add3(float3 vv, float3 ww) { return make_float3(vv.x + ww.x, vv.y + ww.y, vv.z + ww.z); }
""" % {"KR": KR, "KG": KG, "KB": KB}


def _assemble(ui: str, body: str, key_cube: str | None) -> str:
    lut = f"DEFINE_LUT(keyLut, {key_cube})\n" if key_cube else ""   # unquoted: Resolve keeps quotes as part of the name
    src = _HEADER + ui + lut + _HELPERS + body
    for k, v in _CONST.items():
        src = src.replace(k, v)
    return src


def _slider(var: str, label: str, value: float, lo: float, hi: float, step: float = 0.001) -> str:
    return f"DEFINE_UI_PARAMS({var}, {label}, DCTLUI_SLIDER_FLOAT, {float(value):.6g}, {lo:g}, {hi:g}, {step:g})\n"


@dataclass
class ToneSatParams:
    pivot: float = 0.42
    s: float = 0.0
    sat: float = 1.0
    shadow_sat: float = 1.0
    hi_limit: float = 1.0
    blue: float = 1.0
    sky_hue: float = 0.0
    sky_lift: float = 0.0
    green: float = 1.0
    warm_split: float = 0.0
    lift_stops: float = 0.0      # from LogPrimary: the shadow lift rides at the front of this node
    lift_at: float = 0.0

    @classmethod
    def from_meta(cls, meta: dict) -> "ToneSatParams":
        t, p = meta["4_tone_sat"], meta["3_primary"]
        return cls(pivot=t["pivot"], s=t["s"], sat=t["sat"], shadow_sat=t["shadow_sat"], hi_limit=t["hi_limit"],
                   blue=t["blue"], sky_hue=t["sky_hue"], sky_lift=t["sky_lift"], green=t.get("green", 1.0),
                   warm_split=t.get("warm_split", 0.0), lift_stops=p.get("lift_stops", 0.0), lift_at=p.get("lift_at", 0.0))


def tone_sat(p: ToneSatParams, key_cube: str) -> str:
    """Node 2 on GP-Log codes (after the node-1 CDL): shadow lift, S-curve, saturation and the sky/blue/green keys."""
    ui = (_slider("liftStops", "Shadow lift stops", p.lift_stops, -2, 4)
          + _slider("liftAt", "Shadow lift below log code", p.lift_at, 0, 1)
          + _slider("sCurve", "S curve strength", p.s, -0.5, 1.5)
          + _slider("pivot", "S curve pivot", p.pivot, 0.05, 0.95)
          + _slider("sat", "Saturation", p.sat, 0, 3)
          + _slider("shadowSat", "Shadow saturation", p.shadow_sat, 0, 2)
          + _slider("hiLimit", "Highlight saturation limit", p.hi_limit, 0, 1)
          + _slider("blueGain", "Blue sky saturation", p.blue, 0, 3)
          + _slider("greenGain", "Green saturation", p.green, 0, 3)
          + _slider("skyHue", "Sky hue toward blue deg", p.sky_hue, -45, 45, 0.1)
          + _slider("skyLift", "Sky lift stops", p.sky_lift, -2, 2)
          + _slider("warmSplit", "Warm split sunlit vs shade", p.warm_split, -1, 1))
    body = f"""
__DEVICE__ float fpv_curve(float uu, float pv, float st) {{
    float pp = _clampf(pv, 0.05f, 0.95f), kk = 1.0f + st, uc = fpv_clamp01(uu);
    float cc = uc < pp ? pp * _powf(uc / pp, kk) : 1.0f - (1.0f - pp) * _powf((1.0f - uc) / (1.0f - pp), kk);
    return uu > 1.0f ? uu : cc;
}}

__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)
{{
    float3 rgb = make_float3(p_R, p_G, p_B);

    // --- shadow-only lift on scene light (LogPrimary.shadow)
    if (liftStops != 0.0f) {{
        float3 v = fpv_clamp3(rgb);
        float3 lin = make_float3((_powf(400.0f, v.x) - 1.0f) / 399.0f, (_powf(400.0f, v.y) - 1.0f) / 399.0f, (_powf(400.0f, v.z) - 1.0f) / 399.0f);
        float n = (lin.x + lin.y + lin.z) / 3.0f;
        float t = (_powf(400.0f, liftAt) - 1.0f) / 399.0f;
        float gl = 1.0f + (_powf(2.0f, liftStops) - 1.0f) * _powf(t / (n + t), 2.0f);
        lin = fpv_max3(fpv_mulf(lin, gl), 0.0f);
        rgb = fpv_mulf(make_float3(_logf(lin.x * 399.0f + 1.0f), _logf(lin.y * 399.0f + 1.0f), _logf(lin.z * 399.0f + 1.0f)), 1.0f / _logf(400.0f));
    }}

    // --- the displayed colour (through the CST) keys every qualifier below
    float3 disp = APPLY_LUT(rgb.x, rgb.y, rgb.z, keyLut);
    float yd = fpv_luma(disp);
    float cbd = (disp.z - yd) / 1.8556f, crd = (disp.x - yd) / 1.5748f;
    float hue = _atan2f(crd, cbd) * 180.0f / FPV_PI;
    float c = _sqrtf(cbd * cbd + crd * crd);

    // --- S-curve on log luma, channel ratios kept
    float y0 = (rgb.x + rgb.y + rgb.z) / 3.0f;
    if (sCurve != 0.0f) {{
        float yc = _clampf(y0, 0.0001f, 1.0f);
        rgb = fpv_max3(fpv_mulf(rgb, fpv_curve(yc, pivot, sCurve) / _fmaxf(y0, 0.0001f)), 0.0f);
    }}

    // --- log chroma about the grey axis
    float m = (rgb.x + rgb.y + rgb.z) / 3.0f;
    float3 d = fpv_addf(rgb, -m);
    if (skyHue != 0.0f) {{
        float w = fpv_clamp01(1.0f - _fabs(hue + 45.0f) / 30.0f) * fpv_clamp01((yd - 0.45f) / 0.15f);
        float rot = w * skyHue * FPV_PI / 180.0f;
        float k = 0.57735027f, cs = _cosf(rot), sn = _sinf(rot);
        float dk = (d.x + d.y + d.z) * k;
        float3 cross = make_float3(k * d.z - k * d.y, k * d.x - k * d.z, k * d.y - k * d.x);
        float kk = k * dk * (1.0f - cs);
        d = fpv_add3(fpv_add3(fpv_mulf(d, cs), fpv_mulf(cross, sn)), make_float3(kk, kk, kk));
    }}
    float cw = fpv_clamp01(c / 0.03f);
    float wBlue = _powf(fpv_clamp01(1.0f - _fabs(fpv_wrap180(hue + 12.0f)) / 35.0f), 1.5f) * cw;
    float g = sat * (1.0f + wBlue * (blueGain - 1.0f));
    float wGreen = fpv_clamp01(1.0f - _fabs(fpv_wrap180(hue + 135.0f)) / 40.0f) * cw;
    g = g * (1.0f + wGreen * (greenGain - 1.0f));
    if (warmSplit != 0.0f) {{
        float wWarm = fpv_clamp01(1.0f - _fabs(hue - 130.0f) / 50.0f);
        g = g * (1.0f + warmSplit * wWarm * _clampf((yd - 0.45f) / 0.25f, -1.0f, 1.0f));
    }}
    g = g * (1.0f - (1.0f - shadowSat) * fpv_clamp01((0.12f - yd) / 0.06f));
    g = g * (1.0f - (1.0f - hiLimit) * fpv_clamp01((yd - 0.75f) / 0.2f));
    float3 out = fpv_addf(fpv_mulf(d, g), m);
    if (skyLift != 0.0f) {{
        float w = fpv_clamp01(1.0f - _fabs(hue + 30.0f) / 50.0f) * fpv_clamp01((yd - 0.25f) / 0.1f) * fpv_clamp01(c / 0.02f);
        out = fpv_addf(out, w * skyLift * FPV_STOP);
    }}
    float3 res = fpv_clamp3(out);
    return make_float3(res.x, res.y, res.z);   // Resolve's parser wants a literal make_float3 on the main return
}}
"""
    return _assemble(ui, body, key_cube)


def look(vibrance: float, key_cube: str) -> str:
    """Node 3 on GP-Log codes: vibrance (muted colours first), keyed on the displayed chroma."""
    ui = _slider("vibrance", "Vibrance", vibrance, -1, 2)
    body = f"""
__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)
{{
    float3 rgb = make_float3(p_R, p_G, p_B);
    if (vibrance != 0.0f) {{
        float3 disp = APPLY_LUT(p_R, p_G, p_B, keyLut);
        float yd = fpv_luma(disp);
        float cb = (disp.z - yd) / 1.8556f, cr = (disp.x - yd) / 1.5748f;
        float g = 1.0f + vibrance * fpv_clamp01(1.0f - _sqrtf(cb * cb + cr * cr) / 0.15f);
        float m = (rgb.x + rgb.y + rgb.z) / 3.0f;
        rgb = fpv_addf(fpv_mulf(fpv_addf(rgb, -m), g), m);
    }}
    float3 res = fpv_clamp3(rgb);
    return make_float3(res.x, res.y, res.z);   // Resolve's parser wants a literal make_float3 on the main return
}}
"""
    return _assemble(ui, body, key_cube)


def unify(u: dict) -> str:
    """Node 5 on Rec.709 (after the CST): the reel-wide match (Unify.apply)."""
    ui = (_slider("lift", "Lift", u["lift"], -0.3, 0.3)
          + _slider("gain", "Gain", u["gain"], 0.5, 2)
          + _slider("power", "Power 1 over gamma", u["power"], 0.5, 2)
          + _slider("rockRot", "Rock hue rotate deg", u["rock_rot"], -30, 30, 0.1)
          + _slider("rockScale", "Rock saturation", u["rock_scale"], 0, 2)
          + _slider("chromaScale", "Overall saturation", u["chroma_scale"], 0, 2))
    body = """
__DEVICE__ float3 transform(int p_Width, int p_Height, int p_X, int p_Y, float p_R, float p_G, float p_B)
{
    float3 rgb = make_float3(p_R, p_G, p_B);
    float y0 = fpv_luma(rgb);
    float yt = _powf(fpv_clamp01(lift + gain * fpv_clamp01(y0)), power);
    rgb = fpv_clamp3(fpv_mulf(rgb, yt / _fmaxf(y0, 0.0001f)));
    float y = fpv_luma(rgb);
    float cb = (rgb.z - y) / 1.8556f, cr = (rgb.x - y) / 1.5748f;
    float hue = _atan2f(cr, cb) * 180.0f / FPV_PI;
    float c = _sqrtf(cb * cb + cr * cr);
    float w = fpv_clamp01(1.0f - _fabs(hue - 130.0f) / 50.0f) * fpv_clamp01(c / 0.03f);
    float rot = w * rockRot * FPV_PI / 180.0f;
    float cs = _cosf(rot), sn = _sinf(rot);
    float cb2 = cb * cs - cr * sn, cr2 = cb * sn + cr * cs;
    float g = chromaScale * (1.0f + w * (rockScale - 1.0f));
    float3 res = fpv_clamp3(fpv_from_ycc(y, cb2 * g, cr2 * g));
    return make_float3(res.x, res.y, res.z);   // Resolve's parser wants a literal make_float3 on the main return
}
"""
    return _assemble(ui, body, None)


def write_all(meta: dict, folder, key_cube: str, stem: str = "n") -> dict[int, str]:
    """Write node 2 / 3 / 5 DCTLs for one shot into `folder` (where `key_cube` already is). Returns {node: filename}."""
    from pathlib import Path
    folder = Path(folder)
    out = {}
    (folder / f"{stem}2_TONE_SAT.dctl").write_text(tone_sat(ToneSatParams.from_meta(meta), key_cube), encoding="utf-8")
    out[2] = f"{stem}2_TONE_SAT.dctl"
    (folder / f"{stem}3_LOOK.dctl").write_text(look(float(meta["5_look"].get("vibrance", 0.0)), key_cube), encoding="utf-8")
    out[3] = f"{stem}3_LOOK.dctl"
    if meta.get("unify"):
        (folder / f"{stem}5_UNIFY.dctl").write_text(unify(meta["unify"]), encoding="utf-8")
        out[5] = f"{stem}5_UNIFY.dctl"
    else:
        (folder / f"{stem}5_UNIFY.dctl").unlink(missing_ok=True)
    return out
